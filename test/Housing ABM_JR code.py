    def step(self):
        for agent in self.schedule.agents:
            if not agent.dead:
                probability = self.calculate_probability(agent)
                if random.random() < probability:
                    agent.type = 'Owner'
        self.schedule.step()
        self.datacollector.collect(self)
        # 在模型初始化时统一处理省份名称
        self.housing_price_data = {province.lower(): prices for province, prices in self.housing_price_data.items()}
        self.year += 1  # 年份递增

    def calculate_probability(self, agent):
        # 计算可负担性
        P_affordability = self.calculate_affordability(agent)

        # 如果不可负担，直接返回 0
        if P_affordability <= 0:
            return 0.0

        # 如果affordability满足条件，继续计算其他因素（经济效用和社会规范）
        P_economic = self.calculate_economic(agent)

        # 计算社会规范
        P_norm = self.calculate_norm(agent)

        # 根据三个规则计算总的probability
        beta1, beta2, beta3 = 0.2, 0.0, 0.8
        total_probability = beta1 * P_affordability + beta2 * P_economic + beta3 * P_norm

        # 确保概率在 [0, 1] 范围内（可选）
        return max(0.0, min(1.0, total_probability))

    def calculate_affordability(self, agent):
        # 获取当前年份的房价
        housing_price = self.get_housing_price(agent.province)
        if housing_price is None:
            raise ValueError(f"Housing price data not found for province '{agent.province}'")

        if agent.income == 0:
            return 0  # 如果收入为零，直接认为不可负担

        # 贷款金额
        loan_amount = agent.loan_ratio * housing_price * agent.housing_size

        # 假设贷款利率（4.5%）
        interest_rate = 0.045
        monthly_rate = interest_rate / 12  # 月利率

        # 贷款期限（假设20年，即240个月）
        loan_term_months = 20 * 12

        # 等额本息还款法计算每月还款额
        if loan_amount <= 0 or monthly_rate <= 0 or loan_term_months <= 0:
            raise ValueError("Invalid loan parameters.")

        monthly_payment = (loan_amount * monthly_rate * (1 + monthly_rate) ** loan_term_months) / (
                    (1 + monthly_rate) ** loan_term_months - 1)

        # 年还款额
        annual_payment = monthly_payment * 12

        # 计算收入与住房成本的比例
        income_housing_cost_ratio = agent.income / annual_payment

        # 如果比例大于30%，返回1，否则返回0
        return 1 if income_housing_cost_ratio > 0.3 else 0

    def calculate_economic(self, agent):
        # 计算经济效用
        P0 = self.get_initial_price(agent.province)  # 初始房价
        if P0 is None:
            raise ValueError(f"Initial price data not found for province '{agent.province}'")
        # 获取对应省份和年份的市场趋势
        market_trend = self.market_trends[agent.province][self.year - 2003] if self.year - 2003 < len(self.market_trends[agent.province]) else 0

        # 计算经济效用
        economic_indicator = self.gdp_growth_rate[agent.province][self.year]
        local_factor = random.uniform(0, 1)  # 局部因素
        T = self.year - 2003  # 时间（2003-当前年份累计）
        E = P0 * ((1 + market_trend + economic_indicator + local_factor) ** T - 1)
        return E

    def calculate_norm(self, agent):
        # 确保 agent.province 是有效的
        if agent.province not in self.province_distances:
            raise ValueError(f"Invalid province: {agent.province}")

        # 计算社会规范
        ownership_rate = self.calculate_ownership_rates()  # 获取全局所有者比例
        social_influence = agent.social_influence_sensitivity

        # 初始化社会规范影响
        norm_influence = 0

        # 遍历所有省份，计算加权的社会规范影响
        for province in self.province_distances[agent.province].keys():
            # 获取当前省份到代理所在省份的距离权重
            distance_weight = 1 / (1 + self.province_distances[agent.province][province])
            if distance_weight > 0:  # 如果距离权重大于0
                norm_influence += ownership_rate * distance_weight

        # 计算社会规范概率
        norm_probability = 1 / (1 + expit(-social_influence * (norm_influence - 0.5)))
        return norm_probability

    def calculate_ownership_rates(self):
        total_agents = len(self.schedule.agents)
        if total_agents == 0:
            return 0.0
        owner_agents = sum(1 for agent in self.schedule.agents if agent.type == 'Owner')
        return owner_agents / total_agents

    def calculate_renter_rates(self):
        total_agents = len(self.schedule.agents)
        if total_agents == 0:
            return 0.0
        renter_agents = sum(1 for agent in self.schedule.agents if agent.type == 'Renter')
        return renter_agents / total_agents

