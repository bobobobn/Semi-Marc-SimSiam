# 定义代理类 HousingAgent
class HousingAgent(Agent):
    def __init__(self, unique_id, model, age, income, type, province, social_influence_sensitivity, loan_ratio, housing_size):
        super().__init__(unique_id, model)
        self.age = age
        self.income = income
        self.type = type  # 'Owner' or 'Renter'
        self.province = province
        self.social_influence_sensitivity = social_influence_sensitivity
        self.loan_ratio = loan_ratio  # 贷款比例
        self.housing_size = housing_size  # 住房大小
        self.dead = False  # 标记是否死亡

    def update_income(self):
        # 每年更新收入，8.7%的增长率
        self.income *= 1.087

    def update_age(self):
        # 每年更新年龄
        self.age += 1
        # 检查死亡概率
        death_prob = self.model.death_probability.get(self.age, 0)
        if random.random() < death_prob:
            self.dead = True

    def step(self):
        # 更新收入和年龄
        self.update_income()
        self.update_age()
        if self.dead:
            # 如果死亡，移除当前代理并创建新的代理
            self.model.schedule.remove(self)
            new_agent = self.model.create_new_agent(self.province)
            self.model.schedule.add(new_agent)
            # 替换当前位置的代理
            self.model.grid.place_agent(new_agent, self.pos)


